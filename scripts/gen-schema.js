// Generates `src/schemaData.ts` from `schema/schema-v4.json`.
//
// The sprite schema is the single source of truth for the codec: it carries,
// for every set field, the number of types, the number of patterns per type
// and the effective colour count of every (type, pattern) pair.
//
// Runs on Node 9 (no template literals in the output, plain ES5-ish TS).
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'schema', 'schema-v4.json');
const OUT = path.join(ROOT, 'src', 'schemaData.ts');

function main() {
	if (!fs.existsSync(SRC)) {
		throw new Error('Missing schema: ' + SRC + ' (run scripts/extract-schema.js first)');
	}

	const schema = JSON.parse(fs.readFileSync(SRC, 'utf8'));

	const fields = schema.setFields.map(f => ({
		name: f.name,
		preserveOnZero: !!f.preserveOnZero,
		minColors: f.minColors || 0,
		types: f.types.map(t => t === null ? null : t.map(p => p.colors)),
	}));

	const lines = [];
	lines.push('// AUTO-GENERATED by scripts/gen-schema.js from schema/schema-v4.json');
	lines.push('// Source: ' + schema.source + ' (v' + schema.version + ')');
	lines.push('// Do not edit manually - run `npm run gen-schema` instead.');
	lines.push('');
	lines.push('export const schemaVersion: string = ' + JSON.stringify(schema.version) + ';');
	lines.push('export const schemaSource: string = ' + JSON.stringify(schema.source) + ';');
	lines.push('');
	lines.push('export interface SchemaSetFieldEntry {');
	lines.push('\tname: string;');
	lines.push('\tpreserveOnZero: boolean;');
	lines.push('\tminColors: number;');
	lines.push('\t// types[type][pattern] = effective colour count, null = missing type');
	lines.push('\ttypes: (number[] | null)[];');
	lines.push('}');
	lines.push('');
	lines.push('export const schemaSetFields: SchemaSetFieldEntry[] = ' + JSON.stringify(fields, null, '\t') + ';');
	lines.push('');

	fs.writeFileSync(OUT, lines.join('\n'));

	console.log('src/schemaData.ts written (' + fs.statSync(OUT).size + ' bytes)');
}

main();
