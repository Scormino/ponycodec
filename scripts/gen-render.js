// Generates `src/renderData.ts` from `schema/render-v1.json`.
//
// The render schema carries the *merged* sets used by the renderer (the codec
// uses the raw ones), the extra palettes of the face accessory, the default
// palette and the water palette.
//
// Runs on Node 9 (plain ES5-ish TS output).
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'schema', 'render-v1.json');
const OUT = path.join(ROOT, 'src', 'renderData.ts');

function main() {
	if (!fs.existsSync(SRC)) {
		throw new Error('Missing render schema: ' + SRC + ' (run scripts/extract-render.js first)');
	}

	const schema = JSON.parse(fs.readFileSync(SRC, 'utf8'));

	const sets = schema.sets.map(s => ({
		name: s.name,
		extra: !!s.extra,
		// types[type][pattern] = { colors, color, extra, palettes } | null
		types: s.types.map(t => t === null ? null : t.map(p => p === null ? null : {
			colors: p.colors,
			color: p.color,
			extra: p.extra,
			palettes: p.palettes,
		})),
	}));

	const lines = [];
	lines.push('// AUTO-GENERATED by scripts/gen-render.js from schema/render-v1.json');
	lines.push('// Source: ' + schema.source + ' (v' + schema.version + ')');
	lines.push('// Do not edit manually - run `npm run gen-render` instead.');
	lines.push('');
	lines.push('export interface RenderSprite {');
	lines.push('\tx: number;');
	lines.push('\ty: number;');
	lines.push('\tw: number;');
	lines.push('\th: number;');
	lines.push('\tox: number;');
	lines.push('\toy: number;');
	lines.push('\t// the tint of the sprite (0 = white, 1 = far colour, ...)');
	lines.push('\ttype: number;');
	lines.push('}');
	lines.push('');
	lines.push('export interface RenderPattern {');
	lines.push('\t// effective number of fill colours of the pattern');
	lines.push('\tcolors: number;');
	lines.push('\t// the sprite that is drawn with the palette of the set');
	lines.push('\tcolor: RenderSprite | null;');
	lines.push('\t// the sprite that is drawn with the extra palette (face accessory)');
	lines.push('\textra: RenderSprite | null;');
	lines.push('\t// extra palettes of the pattern (only the face accessory uses them)');
	lines.push('\tpalettes: number[][] | null;');
	lines.push('}');
	lines.push('');
	lines.push('export interface RenderSet {');
	lines.push('\tname: string;');
	lines.push('\textra: boolean;');
	lines.push('\t// types[type][pattern] = pattern data, null = missing type');
	lines.push('\ttypes: (RenderPattern[] | null)[];');
	lines.push('}');
	lines.push('');
	lines.push('export const renderVersion: string = ' + JSON.stringify(schema.version) + ';');
	lines.push('export const renderDefaultPalette: number[] = ' + JSON.stringify(schema.defaultPalette) + ';');
	lines.push('export const renderWaterPalette: number[] = ' + JSON.stringify(schema.waterPalette) + ';');
	lines.push('');
	lines.push('export const renderSets: RenderSet[] = ' + JSON.stringify(sets, null, '\t') + ';');
	lines.push('');

	fs.writeFileSync(OUT, lines.join('\n'));

	console.log('src/renderData.ts written (' + fs.statSync(OUT).size + ' bytes)');
}

main();
