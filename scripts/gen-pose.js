// Generates `src/poseData.ts` from `schema/pose-v1.json`.
//
// The pose schema carries the sprite rectangles of every part that is drawn in
// the standing pose, the part offsets and the constants of the layout.
//
// Runs on Node 9 (plain ES5-ish TS output).
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'schema', 'pose-v1.json');
const OUT = path.join(ROOT, 'src', 'poseData.ts');

function main() {
	if (!fs.existsSync(SRC)) {
		throw new Error('Missing pose schema: ' + SRC + ' (run scripts/extract-pose.js first)');
	}

	const schema = JSON.parse(fs.readFileSync(SRC, 'utf8'));

	const lines = [];
	lines.push('// AUTO-GENERATED by scripts/gen-pose.js from schema/pose-v1.json');
	lines.push('// Do not edit manually - run `npm run gen-pose` instead.');
	lines.push('');
	lines.push('import { RenderSprite } from \'./renderData\';');
	lines.push('');
	lines.push('export interface PoseSprite extends RenderSprite {');
	lines.push('\t// the index of the sprite sheet that contains the sprite');
	lines.push('\tsheet: number;');
	lines.push('}');
	lines.push('');
	lines.push('export interface PosePattern {');
	lines.push('\tcolors: number;');
	lines.push('\tcolor: PoseSprite | null;');
	lines.push('\textra: PoseSprite | null;');
	lines.push('}');
	lines.push('');
	lines.push('export interface PoseSet {');
	lines.push('\t// types[type][pattern] = pattern data, null = missing type');
	lines.push('\ttypes: (PosePattern[] | null)[];');
	lines.push('}');
	lines.push('');
	lines.push('export interface PoseNoseSet {');
	lines.push('\ttypes: (PoseNose[] | null)[];');
	lines.push('}');
	lines.push('');
	lines.push('export interface PoseEye {');
	lines.push('\tbase: PoseSprite | null;');
	lines.push('\tirises: (PoseSprite | null)[] | null;');
	lines.push('\tshadow: PoseSprite | null;');
	lines.push('\tshine: PoseSprite | null;');
	lines.push('}');
	lines.push('');
	lines.push('export interface PoseNose {');
	lines.push('\tcolors: number;');
	lines.push('\tcolor: PoseSprite | null;');
	lines.push('\tmouth: PoseSprite | null;');
	lines.push('\tfangs: PoseSprite | null;');
	lines.push('}');
	lines.push('');
	lines.push('export interface PosePoint {');
	lines.push('\tx: number;');
	lines.push('\ty: number;');
	lines.push('}');
	lines.push('');
	lines.push('export const poseConstants = ' + JSON.stringify(schema.constants, null, '\t') + ' as {');
	lines.push('\tponyWidth: number;');
	lines.push('\tponyHeight: number;');
	lines.push('\tfarOx: number;');
	lines.push('\tfarOy: number;');
	lines.push('\tfarWingOx: number;');
	lines.push('\tfarWingOy: number;');
	lines.push('\tshadowOx: number;');
	lines.push('\tshadowOy: number;');
	lines.push('\tfarColor: number;');
	lines.push('\twhite: number;');
	lines.push('\tshinesColor: number;');
	lines.push('};');
	lines.push('');
	lines.push('export const poseFrame = ' + JSON.stringify(schema.frame, null, '\t') + ';');
	lines.push('');
	lines.push('export const poseHeadFrame = ' + JSON.stringify(schema.headFrame, null, '\t') + ';');
	lines.push('');

	const offsets = {};
	for (const key of Object.keys(schema.offsets)) {
		offsets[key] = schema.offsets[key].map(p => ({ x: p[0], y: p[1] }));
	}
	lines.push('export const poseOffsets: { [name: string]: PosePoint[] } = ' + JSON.stringify(offsets, null, '\t') + ';');
	lines.push('');

	const setNames = [
		'body', 'head0', 'head1', 'ears', 'earsFar', 'horns', 'hornsBehind',
		'behindManes', 'topManes', 'frontManes', 'backBehindManes', 'backFrontManes',
		'facialHair', 'facialHairBehind', 'headAccessories', 'headAccessoriesBehind',
		'earAccessories', 'earAccessoriesBehind', 'faceAccessories', 'faceAccessories2',
		'extraAccessories', 'extraAccessoriesBehind',
		'frontLegs', 'backLegs', 'backLegs2', 'frontLegHooves', 'claws', 'backLegHooves', 'backLegHooves2',
		'frontLegAccessories', 'backLegAccessories', 'backLegAccessories2',
		'frontLegSleeves', 'backLegSleeves', 'backLegSleevesMerged', 'backLegSleeves2',
		'tails', 'neckAccessories', 'backAccessories', 'waistAccessories', 'chest', 'chestBehind', 'wings',
	];

	const sprites = {};
	for (const key of Object.keys(schema.sprites)) {
		const value = schema.sprites[key];
		if (setNames.indexOf(key) >= 0) {
			sprites[key] = { types: value || [] };
		} else if (key === 'noses') {
			sprites[key] = value.map(types => ({ types: types }));
		} else {
			sprites[key] = value;
		}
	}

	lines.push('export const poseSprites = ' + JSON.stringify(sprites, null, '\t') + ' as unknown as {');
	lines.push('\tbody: PoseSet;');
	lines.push('\thead0: PoseSet;');
	lines.push('\thead1: PoseSet;');
	lines.push('\tears: PoseSet;');
	lines.push('\tearsFar: PoseSet;');
	lines.push('\thorns: PoseSet;');
	lines.push('\thornsBehind: PoseSet;');
	lines.push('\tbehindManes: PoseSet;');
	lines.push('\ttopManes: PoseSet;');
	lines.push('\tfrontManes: PoseSet;');
	lines.push('\tbackBehindManes: PoseSet;');
	lines.push('\tbackFrontManes: PoseSet;');
	lines.push('\tfacialHair: PoseSet;');
	lines.push('\tfacialHairBehind: PoseSet;');
	lines.push('\theadAccessories: PoseSet;');
	lines.push('\theadAccessoriesBehind: PoseSet;');
	lines.push('\tearAccessories: PoseSet;');
	lines.push('\tearAccessoriesBehind: PoseSet;');
	lines.push('\tfaceAccessories: PoseSet;');
	lines.push('\tfaceAccessories2: PoseSet;');
	lines.push('\textraAccessories: PoseSet;');
	lines.push('\textraAccessoriesBehind: PoseSet;');
	lines.push('\tfrontLegs: PoseSet;');
	lines.push('\tbackLegs: PoseSet;');
	lines.push('\tbackLegs2: PoseSet;');
	lines.push('\tfrontLegHooves: PoseSet;');
	lines.push('\tclaws: PoseSet;');
	lines.push('\tbackLegHooves: PoseSet;');
	lines.push('\tbackLegHooves2: PoseSet;');
	lines.push('\tfrontLegAccessories: PoseSet;');
	lines.push('\tbackLegAccessories: PoseSet;');
	lines.push('\tbackLegAccessories2: PoseSet;');
	lines.push('\tfrontLegSleeves: PoseSet;');
	lines.push('\tbackLegSleeves: PoseSet;');
	lines.push('\tbackLegSleevesMerged: PoseSet;');
	lines.push('\tbackLegSleeves2: PoseSet;');
	lines.push('\ttails: PoseSet;');
	lines.push('\tneckAccessories: PoseSet;');
	lines.push('\tbackAccessories: PoseSet;');
	lines.push('\twaistAccessories: PoseSet;');
	lines.push('\tchest: PoseSet;');
	lines.push('\tchestBehind: PoseSet;');
	lines.push('\twings: PoseSet;');
	lines.push('\tnoses: PoseNoseSet[];');
	lines.push('\teyeLeft: ((PoseEye | null)[] | null)[];');
	lines.push('\teyeRight: ((PoseEye | null)[] | null)[];');
	lines.push('\tcms: PoseSprite | null;');
	lines.push('\tcmsFlip: PoseSprite | null;');
	lines.push('\tponyShadows: (PoseSprite | null)[];');
	lines.push('\tponySelections: (PoseSprite | null)[];');
	lines.push('};');
	lines.push('');

	fs.writeFileSync(OUT, lines.join('\n'));

	console.log('src/poseData.ts written (' + fs.statSync(OUT).size + ' bytes)');
}

main();
